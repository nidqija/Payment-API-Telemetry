CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Matches Model.Merchant
CREATE TABLE IF NOT EXISTS merchants (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    webhook_url TEXT,
    webhook_secret VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Matches Model.ApiKey
CREATE TABLE IF NOT EXISTS api_keys (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    merchant_id UUID NOT NULL REFERENCES merchants(id) ON DELETE CASCADE,
    key_prefix VARCHAR(16) NOT NULL,
    short_id VARCHAR(16) NOT NULL,
    hashed_secret VARCHAR(64) NOT NULL,
    environment VARCHAR(10) NOT NULL DEFAULT 'test',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_used_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS payments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    merchant_id UUID NOT NULL REFERENCES merchants(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(255) NOT NULL,
    amount INT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    customer_email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);



CREATE TABLE IF NOT EXISTS idempotency_records (

    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    merchant_id UUID NOT NULL REFERENCES merchants(id) ON DELETE CASCADE, -- required for merchant lookup for idempotency key
    payment_id UUID REFERENCES payments(id) ON DELETE SET NULL, -- required for payment lookup for idempotency key
    idempotency_key VARCHAR(255) NOT NULL, -- generated by the client to ensure idempotency of requests

    request_path VARCHAR(64) NOT NULL DEFAULT '/v1/payments', -- the api path of the request 
    request_method VARCHAR(10) NOT NULL DEFAULT 'POST', -- the http method of the request
    request_hash VARCHAR(64) NOT NULL, -- the hash of the request body to ensure that the same request is being retried

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING', -- the status of the idempotency record (PENDING , COMPLETED , FAILED)
    locked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), -- the time when the record was locked for processing
    recovery_token UUID NOT NULL DEFAULT gen_random_uuid(), -- recovery token to be used for retrying the request in case of failure

    response_code INT, -- response code of the request 
    response_headers JSONB, -- response headers of the request
    response_body JSONB, -- response body of the request


    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), -- the time when the record was created
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), -- the time when the record was last updated
    expires_at TIMESTAMPTZ NOT NULL DEFAULT NOW() + INTERVAL '24 hour', -- the time when the record expires

    CONSTRAINT uq_merchant_idempotency_key UNIQUE (merchant_id, idempotency_key) -- unique constraint to ensure that the same idempotency key is not used for the same merchant
);


CREATE TABLE IF NOT EXISTS webhook_callback (
        id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
        payment_id UUID NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
        target_url TEXT NOT NULL,
        event_type VARCHAR(50) NOT NULL,
        payload JSONB NOT NULL,
        http_status_code TEXT NOT NULL, -- the http status code of the response from the merchant
        request_headers JSONB NOT NULL,
        response_body TEXT,
        delivered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        duration_ms BIGINT

);


CREATE INDEX IF NOT EXISTS idx_idem_merchant_lookup ON idempotency_records(merchant_id , idempotency_key); -- index to speed up the lookup of idempotency records by merchant_id and idempotency_key
CREATE INDEX IF NOT EXISTS idx_idem_payment_lookup ON idempotency_records(payment_id , idempotency_key); -- index to speed up the lookup of idempotency records by payment_id
CREATE INDEX IF NOT EXISTS idx_idem_expires_at ON idempotency_records(expires_at) WHERE status = 'COMPLETED'; -- index to speed up the lookup of expired idempotency records that are completed
CREATE INDEX IF NOT EXISTS idx_webhook_deliveries_payment_id ON webhook_callback(payment_id); -- index to speed up searching of webhook deliveries by payment_id
CREATE INDEX IF NOT EXISTS idx_webhook_deliveries_created_at ON webhook_callback(delivered_at); -- index to speed up the lookup of webhook deliveries according to delivered at column

